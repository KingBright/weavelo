#[test]
fn test_rpcrypt_ps5_cfb_roundtrip_and_zero_keystream() {
    let nonce = [
        0xae, 0x92, 0xe7, 0x64, 0x88, 0x26, 0x51, 0xef, 0x89, 0x01, 0x8c, 0xfa, 0x69, 0x6c, 0x69,
        0x38,
    ];
    let morning = [
        0x74, 0xa5, 0x9c, 0x96, 0x93, 0xc2, 0x08, 0x3b, 0xa6, 0xa8, 0x4b, 0xa0, 0x50, 0xfa, 0x8e,
        0x5a,
    ];
    let rpc = Rpcrypt::init_auth_ps5(&nonce, &morning);
    for len in [4usize, 16, 20, 32, 800] {
        let plain: Vec<u8> = (0..len).map(|i| ((i * 37) ^ 0x5a) as u8).collect();
        let enc = rpc.encrypt(7, &plain);
        assert_ne!(enc, plain);
        let dec = rpc.decrypt(7, &enc);
        assert_eq!(dec, plain);
    }

    let aer = aeropause_ps5(0x11, &rpc.ambassador).unwrap();
    let amb_back = ambassador_from_aeropause_ps5(0x11, &aer).unwrap();
    assert_eq!(amb_back, rpc.ambassador);

    let zeros = vec![0u8; 40];
    let ks = rpc.encrypt(3, &zeros);
    let msg = b"hello-ps5-launchspec-payload-zero-xor!!\0";
    let enc = rpc.encrypt_zero_keystream_xor(3, msg);
    let back: Vec<u8> = enc.iter().zip(ks.iter()).map(|(a, b)| a ^ b).collect();
    assert_eq!(back, msg);
}

