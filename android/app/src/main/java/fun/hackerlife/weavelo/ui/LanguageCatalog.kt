    fun resolvePreference(saved: String?, systemLanguage: String): AppLanguage = when (saved) {
        "zh" -> AppLanguage.CHINESE
        "en" -> AppLanguage.ENGLISH
        else -> if (systemLanguage.equals("zh", ignoreCase = true)) AppLanguage.CHINESE else AppLanguage.ENGLISH
    }

    fun text(language: AppLanguage, key: String): String =
        if (language == AppLanguage.CHINESE) chinese[key] ?: key else key

    fun render(language: AppLanguage, value: `fun`.hackerlife.weavelo.AppText): String =
        format(language, value.key, *value.arguments.map { if (it is `fun`.hackerlife.weavelo.AppText) render(language, it) else it }.toTypedArray())

    fun format(language: AppLanguage, key: String, vararg arguments: Any): String =
        if (arguments.isEmpty()) text(language, key) else String.format(java.util.Locale.ROOT, text(language, key), *arguments)
